"""Curated learning routes; membership is independent of physical note placement."""

from dataclasses import dataclass
from pathlib import Path


@dataclass(frozen=True)
class Section:
    title: str
    entries: tuple[tuple[str, str], ...]


def section(title: str, *entries: tuple[str, str]) -> Section:
    return Section(title, entries)


@dataclass(frozen=True)
class Cluster:
    number: int
    title: str
    domain: str
    purpose: str
    prerequisites: tuple[int, ...]
    related: tuple[int, ...]
    sections: tuple[Section, ...]
    secondary: tuple[tuple[str, str], ...] = ()

    @property
    def basename(self) -> str:
        return f"{self.number:02d} — {self.title}"

    @property
    def legacy_basename(self) -> str:
        return f"Кластер - {self.title}"

    @property
    def folder(self) -> Path:
        """Primary physical topic folder inside the topic's domain."""
        return Path("01 Knowledge") / self.domain / self.basename

    @property
    def path(self) -> Path:
        return self.folder / f"{self.basename}.md"

    @property
    def parent(self) -> str:
        return "Стеганография" if self.domain.endswith("Steganography") else self.domain.split("/")[-1]


